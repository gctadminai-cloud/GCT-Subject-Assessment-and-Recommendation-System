-- GCT Subject Assessment and Recommendation System
-- PostgreSQL / Supabase Complete Schema & Seed Data
-- SAFE VERSION: walang drop table, hindi nabubura ang existing data

-- 1. PROFILES TABLE
create table if not exists public.profiles (
    id text primary key,
    email text unique not null,
    full_name text not null,
    role text not null check (role in ('student', 'registrar_staff', 'registrar_admin')),
    approval_status text not null default 'approved',
    created_at timestamptz not null default now()
);

-- 2. ACCOUNTS TABLE
create table if not exists public.accounts (
    id text primary key,
    student_id text,
    username text unique not null,
    password_hash text not null,
    role text not null check (role in ('student', 'registrar_staff', 'registrar_admin')),
    status text not null default 'approved',
    created_at timestamptz not null default now()
);

-- 3. STUDENTS TABLE
create table if not exists public.students (
    id text primary key,
    student_id text unique not null,
    full_name text not null,
    email text default '',
    program text not null default 'BSIT',
    year_level integer not null default 1,
    section text default 'A',
    schedule text default 'Schedule 1',
    status text default 'approved',
    verified boolean default false,
    id_front_image text,
    id_back_image text,
    selfie_image text,
    id_front_path text,
    id_back_path text,
    selfie_path text,
    created_at timestamptz not null default now()
);

-- 4. SUBJECTS TABLE
create table if not exists public.subjects (
    id text primary key default ('sub-' || gen_random_uuid()),
    code text not null,
    title text not null,
    units numeric(4,1) not null default 3.0,
    lec_units numeric(4,1) default 2.0,
    lab_units numeric(4,1) default 1.0,
    prerequisites text default 'None',
    program text not null default 'BSIT',
    year_level integer not null default 1,
    semester integer not null default 1,
    created_at timestamptz not null default now()
);

-- 5. PREREQUISITES MAPPING TABLE
create table if not exists public.prerequisites (
    id text primary key default ('prereq-' || gen_random_uuid()),
    subject_id text not null,
    prerequisite_subject_id text not null,
    created_at timestamptz not null default now()
);

-- 6. ACADEMIC RECORDS TABLE (Student Grades)
create table if not exists public.academic_records (
    id text primary key default ('rec-' || gen_random_uuid()),
    student_id text not null,
    subject_id text not null,
    grade numeric(5,3) not null,
    term text not null,
    status text not null default 'passed',
    created_at timestamptz not null default now(),
    constraint academic_records_student_sub_term unique (student_id, subject_id, term)
);

-- 7. RECOMMENDATIONS TABLE
create table if not exists public.recommendations (
    id text primary key default ('rec-batch-' || gen_random_uuid()),
    student_id text not null,
    generated_subjects jsonb not null default '[]'::jsonb,
    eligibility text not null default 'eligible',
    status text not null default 'pending_review',
    reviewed_by text,
    review_notes text,
    generated_at timestamptz not null default now(),
    reviewed_at timestamptz
);

-- 8. SETTINGS TABLE
create table if not exists public.settings (
    id text primary key default ('set-' || gen_random_uuid()),
    key text unique not null,
    value text not null,
    description text,
    created_at timestamptz not null default now()
);

-- 9. CHAT LOGS TABLE
create table if not exists public.chat_logs (
    id bigint generated by default as identity primary key,
    student_id text not null,
    role text not null,
    message text not null,
    created_at timestamptz not null default now()
);

-- 10. GRADE RECORDS TABLE (For Bulk CSV Grade Imports)
create table if not exists public.grade_records (
    id bigint generated by default as identity primary key,
    student_id text not null,
    last_name text not null,
    first_name text not null,
    full_name text not null,
    course text not null,
    year_level integer,
    semester text not null,
    academic_year text not null,
    subject text not null,
    grade numeric(5,3),
    units numeric(4,1),
    created_at timestamptz not null default now(),
    constraint grade_records_unique_record unique (student_id, subject, academic_year, semester)
);

-- INDEXES FOR FAST QUERYING
create index if not exists idx_grade_records_student_id on public.grade_records(student_id);
create index if not exists idx_academic_records_student_id on public.academic_records(student_id);
create index if not exists idx_recommendations_student_id on public.recommendations(student_id);

